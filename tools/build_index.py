#!/usr/bin/env python3
"""Regenerate INDEX.md: open to-dos, notes by project, notes by tag, and a day list.

  python tools/build_index.py
  python tools/build_index.py --root examples/sample-lab

Tags come from the front matter `tags:` list plus inline #tags in the text.
"""
from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from labnotes import REPO_ROOT, first_heading, iter_days, scan_note, split_frontmatter  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=REPO_ROOT)
    args = ap.parse_args()
    root = args.root.resolve()

    days, by_tag, by_proj, open_items = [], defaultdict(list), defaultdict(list), []
    for day, path in iter_days(root):
        text = (path / "notes.md").read_text(encoding="utf-8")
        meta, body = split_frontmatter(text)
        todos, inline_tags = scan_note(text)
        rel = (path / "notes.md").relative_to(root).as_posix()
        label = meta.get("summary") or first_heading(body, day)
        entry = (day, rel, label)
        days.append(entry)
        for t in {x.lower() for x in (meta.get("tags") or [])} | inline_tags:
            by_tag[t].append(entry)
        for p in meta.get("projects") or []:
            by_proj[p].append(entry)
        for no, t in todos:
            open_items.append((day, rel, no, t))

    def link(e):
        return "[%s](%s) — %s" % (e[0], e[1], e[2])

    out = ["# Index", "", "_Generated by `tools/build_index.py` — do not edit by hand._", ""]
    out += ["## Open to-dos (%d)" % len(open_items), ""]
    out += ["- [ ] %s — [%s](%s)" % (t, d, rel) for d, rel, _, t in open_items] or ["_None._"]
    out += ["", "## Projects", ""]
    for p in sorted(by_proj):
        out += ["### %s (%d)" % (p, len(by_proj[p]))] + ["- " + link(e) for e in reversed(by_proj[p])] + [""]
    if not by_proj:
        out += ["_None yet._", ""]
    out += ["## Tags", ""]
    for t in sorted(by_tag):
        out += ["### %s (%d)" % (t, len(by_tag[t]))] + ["- " + link(e) for e in reversed(by_tag[t])] + [""]
    if not by_tag:
        out += ["_None yet._", ""]
    out += ["## All days", ""] + ["- " + link(e) for e in reversed(days)] + [""]

    target = root / "INDEX.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print("Wrote %s (%d days, %d tags, %d projects, %d open to-dos)" % (
        target, len(days), len(by_tag), len(by_proj), len(open_items)))


if __name__ == "__main__":
    sys.exit(main())
